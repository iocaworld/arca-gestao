  window.markArcaAgendaAsDeleted = function(id) {
    try {
      let deletedIds = [];
      try {
        deletedIds = JSON.parse(localStorage.getItem(DELETED_AGENDA_KEY) || '[]');
      } catch(e) {}
      if (!deletedIds.includes(Number(id))) {
        deletedIds.push(Number(id));
        localStorage.setItem(DELETED_AGENDA_KEY, JSON.stringify(deletedIds));
      }
    } catch(e) {}
  };

